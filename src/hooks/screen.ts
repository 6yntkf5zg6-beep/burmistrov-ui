/**
 * Большой ли экран — тот же порог, что у `sm` в Tailwind.
 *
 * Отличие «телефон / не телефон» здесь не про вёрстку, а про экранную клавиатуру: она
 * закрывает половину экрана, и поведение, удобное с настоящей клавиатурой, на телефоне
 * мешает. Порог берём тот же, что у вёрстки, чтобы не заводить в проекте второе понятие
 * «мобильной версии».
 *
 * Значение снимают один раз при монтировании: переставлять курсор или менять поведение
 * поля под руками у человека из-за поворота телефона — хуже, чем не отреагировать на него.
 */
export function isWideScreen(): boolean {
  return typeof window !== "undefined" && window.matchMedia("(min-width: 640px)").matches;
}
